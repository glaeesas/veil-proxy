// Copies the runtime pieces Veil needs into public/ so the whole site is a
// static folder: GitHub Pages serves it as-is, and `npm start` serves the same
// folder next to a Wisp server.
//
//   public/uv/uv.bundle.js       Ultraviolet + bare-mux client
//   public/uv/uv.handler.js      injected into every rewritten page
//   public/uv/uv.client.js       the injected page-side runtime
//   public/uv/uv.sw.js           the rewriting service worker
//   public/uv/bare-mux.mjs       BareMuxConnection (page side)
//   public/uv/bare-mux-worker.js SharedWorker that owns the transport
//   public/uv/epoxy.mjs          Epoxy transport (Wisp client)
//   public/uv/epoxy.wasm         its TLS engine
//   public/uv/uv.config.js       generated config, base-path aware
//   public/sw.js                 generated service-worker entry (site root, so
//                                its scope is the whole site without needing a
//                                Service-Worker-Allowed header, which Pages
//                                cannot send)

import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const nm = `${root}node_modules/`;
const out = `${root}public/uv/`;

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

const uvDist = `${nm}@titaniumnetwork-dev/ultraviolet/dist/`;
for (const file of ['uv.bundle.js', 'uv.handler.js', 'uv.client.js', 'uv.sw.js']) {
  await copyFile(uvDist + file, out + file);
}

await copyFile(`${nm}@mercuryworkshop/bare-mux/dist/index.mjs`, `${out}bare-mux.mjs`);
await copyFile(`${nm}@mercuryworkshop/bare-mux/dist/worker.js`, `${out}bare-mux-worker.js`);
await copyFile(`${nm}@mercuryworkshop/epoxy-transport/dist/index.mjs`, `${out}epoxy.mjs`);
await copyFile(`${nm}@mercuryworkshop/epoxy-tls/minimal/epoxy.wasm`, `${out}epoxy.wasm`);

// Paths are derived at runtime from where this file was loaded, so one build
// works at a domain root and at /<repo>/ on GitHub Pages.
const config = `/* Veil — Ultraviolet config. Regenerated by scripts/build.mjs. */
(function () {
  var scope = typeof self !== 'undefined' ? self : this;
  var here = (typeof document !== 'undefined' && document.currentScript && document.currentScript.src) || scope.location.href;
  var root = scope.__uv$base || new URL('./', here).pathname;
  var app = root.replace(/uv\\/$/, '');
  // Absolute URLs: relative ones get resolved against the *target* origin when
  // Ultraviolet writes its runtime script tags into the rewritten document.
  var abs = scope.location.origin + root;
  scope.__uv$config = {
    prefix: app + 'service/',
    encodeUrl: Ultraviolet.codec.xor.encode,
    decodeUrl: Ultraviolet.codec.xor.decode,
    handler: abs + 'uv.handler.js',
    client: abs + 'uv.client.js',
    bundle: abs + 'uv.bundle.js',
    config: abs + 'uv.config.js',
    sw: root + 'uv.sw.js',
    // Page additions (the transport carrier and the toolbar) are injected by
    // public/sw.js after rewriting, not through config.inject: injected markup
    // passes through the URL rewriter and had its paths pointed at the target.
  };
})();
`;

const serviceWorker = `/* Veil — service-worker entry. Regenerated by scripts/build.mjs.
 *
 * Lives at the site root so it may control the whole origin without a
 * Service-Worker-Allowed header, which GitHub Pages cannot set.
 */
// Build stamp: makes the browser pick up config/inject changes on the next
// load instead of serving the previously cached worker scripts.
const VEIL_BUILD = '${new Date().toISOString()}';
self.__uv$base = new URL('./uv/', self.location.href).pathname;
importScripts('./uv/uv.bundle.js', './uv/uv.config.js');
// Separate call: argument expressions are evaluated before importScripts runs,
// so __uv$config.sw does not exist yet on the line above.
importScripts(self.__uv$config.sw);

const uv = new UVServiceWorker();

const APP_ROOT = new URL('./', self.location.href).pathname;

// Veil's own page additions. Ultraviolet can inject scripts into rewritten
// pages, but that markup passes through its URL rewriter, which rewrote
// src="/connect.js" onto the proxied host. Doing it here, after rewriting,
// keeps the paths intact.
const BOOTSTRAP = '<script src="' + APP_ROOT + 'toolbar.js" defer></script>';

// Take over immediately: without a claim the first page load is uncontrolled
// and its subresource requests would fall through to the static server.
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

async function handle(event) {
  if (!uv.route(event)) return fetch(event.request);
  const response = await uv.fetch(event);
  const type = response.headers.get('content-type') || '';
  if (event.request.destination !== 'document' || !type.includes('text/html')) return response;
  const html = await response.text();
  const headers = new Headers(response.headers);
  headers.delete('content-length');
  return new Response(
    html.replace(/<head[^>]*>/i, (tag) => tag + BOOTSTRAP),
    { status: response.status, statusText: response.statusText, headers },
  );
}

self.addEventListener('fetch', (event) => {
  event.respondWith(handle(event));
});
`;

await writeFile(`${out}uv.config.js`, config);
await writeFile(`${root}public/sw.js`, serviceWorker);

const check = ['uv.bundle.js', 'uv.handler.js', 'uv.client.js', 'uv.sw.js', 'uv.config.js', 'bare-mux.mjs', 'bare-mux-worker.js', 'epoxy.mjs', 'epoxy.wasm'];
for (const file of check) {
  const bytes = (await readFile(out + file)).length;
  if (!bytes) throw new Error(`empty build output: ${file}`);
}
const sw = await readFile(`${root}public/sw.js`, 'utf8');
if (!sw.includes('UVServiceWorker')) throw new Error('sw.js missing UVServiceWorker');

console.log(`built public/uv/ (${check.length} files) and public/sw.js`);
